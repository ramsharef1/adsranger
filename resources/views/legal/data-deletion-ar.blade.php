<p>يمكنك في أي وقت إلغاء وصول <bdi dir="ltr">AdsRanger</bdi> إلى حساباتك وطلب حذف بياناتك.</p>

<h2>1. فصل منصة من داخل <bdi dir="ltr">AdsRanger</bdi></h2>
<ol>
<li>سجّل الدخول عبر <a href="https://adsranger.com/app">adsranger.com/app</a>.</li>
<li>افتح <strong>الربط</strong> واختر المنصة ثم اضغط <strong>فصل</strong>.</li>
<li>نحذف رموز الوصول لتلك المنصة فورًا، وبياناتها المجمّعة خلال 30 يومًا.</li>
</ol>

<h2>2. إزالة <bdi dir="ltr">AdsRanger</bdi> من فيسبوك أو إنستغرام</h2>
<ol>
<li>في فيسبوك، اذهب إلى <strong>الإعدادات والخصوصية &gt; الإعدادات &gt; عمليات تكامل الأعمال</strong> (أو التطبيقات ومواقع الويب).</li>
<li>ابحث عن <strong>AdsRanger</strong> واختره ثم اضغط <strong>إزالة</strong>.</li>
<li>فعّل خيار حذف المنشورات أو الفيديوهات أو الفعاليات التي نشرتها <bdi dir="ltr">AdsRanger</bdi> نيابةً عنك إن أردت حذفها أيضًا.</li>
</ol>
<p>تتيح المنصات الأخرى (جوجل وتيك توك وسناب شات ومايكروسوفت ولينكدإن وإكس) إزالة التطبيقات المربوطة من إعدادات الأمان أو التطبيقات بالطريقة نفسها.</p>

<h2>3. طلب حذف جميع بياناتك</h2>
<p>عند حذف المالك لمساحة العمل نغلق الوصول فورًا ونحتفظ بالبيانات 30 يومًا يمكن خلالها استعادتها عبر الدعم، ثم يحذفها فريقنا نهائيًا.</p>
<p>أرسل بريدًا إلى <a href="mailto:privacy@adsranger.com?subject=Data%20deletion%20request">privacy@adsranger.com</a> من البريد المسجّل في حسابك بعنوان «طلب حذف بيانات»، ووضّح إن كنت تريد حذف بيانات منصة واحدة أو حسابك بالكامل.</p>
<ul>
<li>نؤكد استلام الطلب خلال 3 أيام عمل ونعطيك رمزًا مرجعيًا.</li>
<li>تُحذف البيانات خلال 30 يومًا، ثم من النسخ الاحتياطية خلال 30 يومًا إضافية.</li>
<li>قد نحتفظ بسجل مختصر يثبت تنفيذ الطلب، وبما يُلزمنا القانون بالاحتفاظ به مثل الفواتير.</li>
</ul>
