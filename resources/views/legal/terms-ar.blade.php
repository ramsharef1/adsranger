<h2>1. الخدمة</h2>
<p>تتيح <bdi dir="ltr">AdsRanger</bdi> للوكالات والشركات ربط حساباتها الإعلانية وحسابات التواصل، ثم إنشاء الإعلانات والمحتوى العضوي وإدارتها ومتابعتها وإعداد تقاريرها من مكان واحد. تعتمد الميزات على خطتك وقد تتغير مع تطوّر الخدمة.</p>

<h2>2. الحسابات</h2>
<ul>
<li>قدّم بيانات صحيحة وحافظ على سرية كلمة المرور. أنت مسؤول عن النشاط في حسابك ومساحة عملك.</li>
