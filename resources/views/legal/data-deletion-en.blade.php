<p>You can remove AdsRanger's access to your accounts and ask us to delete your data at any time.</p>

<h2>1. Disconnect a platform inside AdsRanger</h2>
<ol>
<li>Sign in at <a href="https://adsranger.com/app">adsranger.com/app</a>.</li>
<li>Open <strong>Connections</strong>, choose the platform and click <strong>Disconnect</strong>.</li>
<li>We delete that platform's access tokens straight away and its collected data within 30 days.</li>
</ol>

<h2>2. Remove AdsRanger from Facebook or Instagram</h2>
<ol>
<li>On Facebook, go to <strong>Settings &amp; privacy &gt; Settings &gt; Business integrations</strong> (or Apps and websites).</li>
<li>Find <strong>AdsRanger</strong>, select it and click <strong>Remove</strong>.</li>
<li>Tick the option to delete posts, videos or events AdsRanger posted on your behalf if you want those removed too.</li>
</ol>
<p>Other platforms (Google, TikTok, Snapchat, Microsoft, LinkedIn, X) let you remove connected apps from their security or app settings in the same way.</p>

<h2>3. Ask us to delete all your data</h2>
<p>Workspace owners can also close and delete their workspace directly inside AdsRanger under <strong>Data &gt; Export data &gt; Delete workspace</strong>, and team members can delete their personal account under <strong>Data &gt; Export data &gt; Delete my account</strong>.</p>
<p>Email <a href="mailto:privacy@adsranger.com?subject=Data%20deletion%20request">privacy@adsranger.com</a> from the address on your account with the subject "Data deletion request". Tell us whether you want one platform's data or your whole account deleted.</p>
<ul>
<li>We confirm within 3 working days and give you a reference code.</li>
<li>Data is deleted within 30 days, and removed from backups within a further 30 days.</li>
<li>We may keep a minimal record that the request was completed, and anything the law requires us to keep, such as invoices.</li>
</ul>
