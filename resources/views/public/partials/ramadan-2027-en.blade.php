<h2>Phase 1: preparation (11 January – 7 February)</h2>
<p>Planning starts before the month. Google reports that one in five people in the region start preparing three to four weeks before Ramadan (<a href="https://business.google.com/en-all/think/consumer-insights/ramadan-2024-retail-marketing-tips/" rel="noopener">Google</a>). For agencies, this is the busiest working window:
- Agree budgets per phase with every client, not one monthly number. To test a budget, use the <a href="/en/tools/ramadan-budget-calculator">Ramadan budget calculator</a>.
- Finish Ramadan and Eid creative in Arabic and English, and leave time for ad review on every network.
- Pull last Ramadan's hour-of-day and day-of-week reports from each account; schedules shift around iftar and suhoor, and each market keeps its own times.
- Set the date of each market in your plan; Gulf countries, the Levant, Egypt and North Africa may start a day apart.
- Plan staff cover for the last ten nights and Eid, when changes are hardest to make.</p>
<h2>Phase 2: the first week (8 – 14 February)</h2>
<p>Demand moves to the evening and late night. Microsoft Advertising reports that occasions and gifts peak in the first half of Ramadan in the Middle East (<a href="https://preview-about.ads.microsoft.com/en/blog/post/february-2025/major-ramadan-trends-and-three-marketing-strategies-to-help-your-brand-excel" rel="noopener">Microsoft Advertising</a>).
- Launch on the confirmed start date in each country, not the earliest one.
- Watch pacing daily: costs and delivery can change fast in the first days.
- Check that schedules follow local evening hours, not the account's default time zone.</p>
<h2>Phase 3: mid-Ramadan (15 – 26 February)</h2>
<p>The middle of the month is the steadiest period. Microsoft Advertising lists finance in the middle of Ramadan, and beauty in the middle and end of the month, as peak times in the region (<a href="https://preview-about.ads.microsoft.com/en/blog/post/february-2025/major-ramadan-trends-and-three-marketing-strategies-to-help-your-brand-excel" rel="noopener">Microsoft Advertising</a>).
- Move budget from weak to strong campaigns weekly, per client.
- Refresh creative that has run since the first week.
- Send clients a mid-month report so Eid decisions are made early.</p>
<h2>Phase 4: the last ten nights (27 February – 8 March)</h2>
<p>Eid shopping, gifts and travel take over. Price matters: 86% of regional consumers see Ramadan as the best time to find deals (<a href="https://business.google.com/en-all/think/consumer-insights/ramadan-2024-retail-marketing-tips/" rel="noopener">Google</a>).
- Put Eid offers live before the rush, not on the last day.
- Keep a reserve budget for the strongest campaigns.
- Confirm who can approve changes during the holiday.</p>
<h2>Phase 5: Eid al-Fitr (from 9 March)</h2>
<ul>
<li>Pause or lower Ramadan-only campaigns once Eid starts in each market.</li>
<li>Run Eid greetings and post-Eid offers on their own budget.</li>
<li>Send the full Ramadan report: results per phase, per network and per market, compared with last year.</li>
</ul>
